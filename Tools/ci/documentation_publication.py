"""Admit only this trusted full run's immutable website to Pages publication.

The publishing job is part of the original CI run, so that run may still be in
progress. Its exact current-attempt full coverage barrier must already have
passed. Release publication retains its separate completed-run requirement.
This helper reads GitHub metadata and extracts an already downloaded site; it
never compiles, converts, uploads, deploys, dispatches or writes to GitHub.
"""

import argparse
import json
import os
from pathlib import Path, PurePosixPath
import re
import subprocess
import sys
import tarfile
import tempfile
from urllib.parse import quote

import artifact_index
from artifact_transfer import Budget, wall_deadline
import github_release
import native_receipts as receipts


TRUSTED_REPOSITORY = "Aurum-Studios/DiscordKit"
WORKFLOW_PATH = ".github/workflows/ci.yml"
SITE_JOB = "Documentation site from validated archives"
SITE_STEP = "Prepare documentation site from sealed conversions"
FULL_JOB = "Offline certification passed"
FULL_STEP = "Verify full scope and complete coverage"
SITE_MARKER = ".discordkit-documentation-site"
MARKER_CONTENT = b"Generated by Tools/ci/build_documentation_site.py\n"
REQUIRED_FILES = {"index.html", "documentation/index.html", ".nojekyll", SITE_MARKER}
MAX_SITE_BYTES = 4 * 1024 * 1024 * 1024
MAX_SITE_MEMBERS = 250000


def positive(value):
    return artifact_index.positive_id(value)


def successful_job(jobs, name, step, *, run_id, attempt, revision):
    """Names select an exact job; API run/attempt/source and its step admit it."""
    matches = [job for job in jobs if isinstance(job, dict) and job.get("name") == name]
    if len(matches) != 1:
        raise ValueError(f"missing or duplicate publication prerequisite: {name}")
    job = matches[0]
    if (not positive(job.get("id")) or str(job.get("run_id")) != run_id
            or job.get("head_sha") != revision
            or "run_attempt" in job and str(job["run_attempt"]) != attempt
            or job.get("status") != "completed" or job.get("conclusion") != "success"):
        raise ValueError(f"unsuccessful or stale publication prerequisite: {name}")
    steps = job.get("steps")
    selected = [item for item in steps if isinstance(item, dict) and item.get("name") == step] if isinstance(steps, list) else []
    if (len(selected) != 1 or selected[0].get("status") != "completed"
            or selected[0].get("conclusion") != "success"):
        raise ValueError(f"publication prerequisite did not verify its complete scope: {step}")
    return str(job["id"])


def current_jobs(api, run_id, attempt):
    """Never let an older successful attempt stand in for this attempt's gate."""
    result, ids = [], set()
    expected = None
    for page in range(1, 1001):
        payload = api.request(f"actions/runs/{run_id}/attempts/{attempt}/jobs?per_page=100&page={page}")
        if (not isinstance(payload, dict) or not isinstance(payload.get("jobs"), list)
                or len(payload["jobs"]) > 100):
            raise ValueError("invalid publication prerequisite job listing")
        # GitHub provides total_count. Small mock/offline snapshots may omit it;
        # when present it must describe a complete stable pagination snapshot.
        if "total_count" in payload:
            count = payload["total_count"]
            if type(count) is not int or count < 0 or expected is not None and count != expected:
                raise ValueError("publication prerequisite listing changed or is incomplete")
            expected = count
        for job in payload["jobs"]:
            if not isinstance(job, dict) or not positive(job.get("id")) or str(job["id"]) in ids:
                raise ValueError("invalid or duplicate publication prerequisite job identity")
            ids.add(str(job["id"]))
        result.extend(payload["jobs"])
        if len(payload["jobs"]) < 100:
            if expected is not None and len(result) != expected:
                raise ValueError("incomplete publication prerequisite listing")
            return result
    raise ValueError("publication prerequisite listing exceeds page limit")


def verify(api, *, execution, revision, mode, artifact_id, artifact_digest, artifact_name,
           producer_attempt):
    """Verify live source trust, current full certification and immutable input ID."""
    receipts.validate_execution(execution)
    if (execution["scope"] != "github" or execution["repository"] != TRUSTED_REPOSITORY
            or api.repository != TRUSTED_REPOSITORY or mode != "full"
            or execution["event"] not in {"push", "workflow_dispatch"}
            or not isinstance(revision, str) or not receipts.SHA1.fullmatch(revision)
            or execution["workflowSHA"] != revision
            or not isinstance(artifact_id, str) or not positive(artifact_id)
            or not isinstance(artifact_digest, str) or not re.fullmatch(r"sha256:[0-9a-f]{64}", artifact_digest)
            or not isinstance(producer_attempt, str) or not positive(producer_attempt)
            or producer_attempt != execution["runAttempt"]):
        raise ValueError("publication requires trusted full same-run/current-attempt source and immutable input identity")
    repository = api.request("")
    if (not isinstance(repository, dict) or repository.get("full_name") != TRUSTED_REPOSITORY
            or str(repository.get("id")) != execution["repositoryID"]
            or repository.get("fork") is not False
            or not isinstance(repository.get("default_branch"), str) or not repository["default_branch"]):
        raise ValueError("publication repository is a fork or its original identity differs")
    branch = repository["default_branch"]
    ref = "refs/heads/" + branch
    if (execution["ref"] != ref
            or execution["workflowRef"] != f"{TRUSTED_REPOSITORY}/{WORKFLOW_PATH}@{ref}"):
        raise ValueError("publication requires the exact default-branch CI workflow and source")
    tip = api.request("git/ref/heads/" + quote(branch, safe=""))
    if (not isinstance(tip, dict) or tip.get("ref") != ref
            or not isinstance(tip.get("object"), dict) or tip["object"].get("type") != "commit"
            or tip["object"].get("sha") != revision):
        raise ValueError("publication source is stale: the default branch now identifies another commit")
    workflow = api.request("actions/workflows/ci.yml")
    run = api.request(f"actions/runs/{execution['runID']}")
    try:
        valid = (positive(workflow["id"]) and workflow["path"] == WORKFLOW_PATH
                 and str(run["id"]) == execution["runID"]
                 and str(run["run_attempt"]) == execution["runAttempt"]
                 and run["workflow_id"] == workflow["id"] and run["path"] == WORKFLOW_PATH
                 and run["event"] == execution["event"] and run["head_sha"] == revision
                 and run["head_branch"] == branch
                 and run["repository"]["full_name"] == TRUSTED_REPOSITORY
                 and str(run["repository"]["id"]) == execution["repositoryID"]
                 and run["head_repository"]["full_name"] == TRUSTED_REPOSITORY
                 and str(run["head_repository"]["id"]) == execution["repositoryID"]
                 and (run["status"] == "in_progress" and run.get("conclusion") is None
                      or run["status"] == "completed" and run.get("conclusion") == "success"))
    except (KeyError, TypeError):
        valid = False
    if not valid:
        raise ValueError("original CI run source, repository, event, workflow, latest attempt or result differs")
    jobs = current_jobs(api, execution["runID"], execution["runAttempt"])
    identity = {"run_id": execution["runID"], "attempt": execution["runAttempt"], "revision": revision}
    full_job = successful_job(jobs, FULL_JOB, FULL_STEP, **identity)
    site_job = successful_job(jobs, SITE_JOB, SITE_STEP, **identity)
    expected_name = f"documentation-site-{revision}-{execution['runID']}-{producer_attempt}"
    if (not isinstance(artifact_name, str)
            or not re.fullmatch(re.escape(expected_name) + r"-t[1-3]", artifact_name)):
        raise ValueError("website artifact name differs from its exact source, run or producer attempt")
    artifact = api.request(f"actions/artifacts/{artifact_id}")
    artifact_index.validate_artifact(artifact, run, execution)
    if (str(artifact["id"]) != artifact_id or artifact["name"] != artifact_name
            or artifact["digest"] != artifact_digest):
        raise ValueError("website immutable artifact ID, name or digest changed")
    # A rerun or a new default-branch commit during admission invalidates this
    # decision. Recheck both immediately before exposing bytes to Pages upload.
    latest = api.request(f"actions/runs/{execution['runID']}")
    if (not isinstance(latest, dict)
            or any(latest.get(key) != run.get(key) for key in ("id", "run_attempt", "head_sha", "status", "conclusion"))):
        raise ValueError("original CI run changed during publication admission")
    if api.request("git/ref/heads/" + quote(branch, safe="")) != tip:
        raise ValueError("default-branch source changed during publication admission")
    return {"schemaVersion": 1, "status": "verified", "mode": "full", "commit": revision,
            "repository": TRUSTED_REPOSITORY, "runID": execution["runID"],
            "runAttempt": execution["runAttempt"], "fullGateJobID": full_job,
            "siteJobID": site_job, "artifact": {"id": artifact_id, "name": artifact_name,
                "digest": artifact_digest, "producerAttempt": producer_attempt}}


def extract_site(archive_path, destination):
    """Admit the complete site tar before staging regular files in a fresh tree."""
    archive_path, destination = Path(archive_path), Path(destination).absolute()
    if (not archive_path.is_file() or archive_path.is_symlink()
            or destination.exists() or destination.is_symlink()
            or any(parent.is_symlink() for parent in destination.parents)):
        raise ValueError("publication site archive/output is missing, linked or already exists")
    required = {"site/" + name for name in REQUIRED_FILES}
    members, names, files, size = [], set(), set(), 0
    try:
        with tarfile.open(archive_path, "r:gz") as archive:
            for member in archive:
                name = member.name.rstrip("/") if member.isdir() else member.name
                path = PurePosixPath(name)
                if (not name or "\\" in name or "\0" in name or path.is_absolute()
                        or any(part in ("", ".", "..") for part in name.split("/"))
                        or str(path) != name or path.parts[0] != "site" or name in names
                        or not (member.isdir() or member.isreg()) or member.sparse is not None
                        or member.size < 0 or member.isdir() and member.size != 0):
                    raise ValueError("unsafe or duplicate website tar member")
                names.add(name)
                members.append((member, name))
                if member.isreg():
                    files.add(name)
                    size += member.size
                if len(members) > MAX_SITE_MEMBERS or size > MAX_SITE_BYTES:
                    raise ValueError("website tar exceeds its bounded extraction size")
            if (not required.issubset(files)
                    or any(str(parent) in files for name in names for parent in PurePosixPath(name).parents)):
                raise ValueError("website tar omits required routes/marker or aliases a file as a directory")
            marker = archive.getmember("site/" + SITE_MARKER)
            if marker.size != len(MARKER_CONTENT) or archive.extractfile(marker).read() != MARKER_CONTENT:
                raise ValueError("website tar has an invalid generated-site marker")
            destination.parent.mkdir(parents=True, exist_ok=True)
            with tempfile.TemporaryDirectory(prefix=".publication-site-", dir=destination.parent) as temporary:
                staged = Path(temporary)
                for member, name in members:
                    target = staged / name
                    if member.isdir():
                        target.mkdir(parents=True, exist_ok=True)
                    else:
                        target.parent.mkdir(parents=True, exist_ok=True)
                        with archive.extractfile(member) as source, target.open("xb") as output:
                            remaining = member.size
                            while remaining:
                                chunk = source.read(min(1024 * 1024, remaining))
                                if not chunk:
                                    raise ValueError("truncated website tar member")
                                output.write(chunk)
                                remaining -= len(chunk)
                if destination.exists() or destination.is_symlink():
                    raise ValueError("website output appeared during extraction")
                (staged / "site").rename(destination)
    except (tarfile.TarError, EOFError) as error:
        raise ValueError("invalid website tar archive") from error
    return {"files": len(files), "bytes": size}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repository", type=Path, default=Path("."))
    parser.add_argument("--mode", required=True)
    parser.add_argument("--artifact-id", required=True)
    parser.add_argument("--artifact-digest", required=True)
    parser.add_argument("--artifact-name", required=True)
    parser.add_argument("--producer-attempt", required=True)
    parser.add_argument("--site-archive", type=Path)
    parser.add_argument("--site-output", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args(argv)
    report = {"schemaVersion": 1, "status": "rejected"}
    try:
        if bool(args.site_archive) != bool(args.site_output):
            raise ValueError("website archive and fresh output must be supplied together")
        with wall_deadline(Budget().remaining()):
            repository = args.repository.resolve()
            execution = receipts.execution_identity(repository)
            revision = os.environ["GITHUB_SHA"]
            checkout = subprocess.check_output(["git", "-C", str(repository), "rev-parse", "HEAD"],
                                               text=True, timeout=30).strip()
            if checkout != revision:
                raise ValueError("publication checkout differs from the original source commit")
            report = verify(github_release.GitHubAPI(), execution=execution, revision=revision, mode=args.mode,
                            artifact_id=args.artifact_id, artifact_digest=args.artifact_digest,
                            artifact_name=args.artifact_name, producer_attempt=args.producer_attempt)
            if args.site_archive:
                report["site"] = extract_site(args.site_archive, args.site_output)
    except (ValueError, RuntimeError, OSError, KeyError, TypeError, subprocess.SubprocessError) as error:
        report.update(status="rejected", error=str(error))
        return 1
    finally:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(json.dumps(report, indent=2, sort_keys=True) + "\n")
        print(json.dumps(report, sort_keys=True))
    return 0


if __name__ == "__main__":
    sys.exit(main())
